/**
 * Localized strings for the translated calculator pages
 * (src/pages/[locale]/calculator/[slug].astro).
 *
 * Kept out of locales.ts on purpose: that registry carries the chrome shared
 * by every localized surface (widget, savings tool, page furniture), while
 * everything here belongs to one page. Same rules, though — UI copy lives
 * here per locale, marketing copy stays per program in airlines.json, and a
 * locale ships translated by the model until a native speaker reviews it
 * (tracked the same way as the buy-page translations).
 *
 * WRITE THESE IN THE LANGUAGE, NOT FROM THE ENGLISH. The first pass rendered
 * the English sentence structure word by word and it read as machine output:
 * relative clauses where the language wants a compound, "above X the miles
 * beat the fare" with no stated subject, and "our purchase price" for what
 * the visitor pays us. If a sentence cannot be re-read aloud naturally by a
 * speaker of the language, rewrite it rather than tightening the translation.
 *
 * Placeholders are pre-formatted by the template before insertion. Note that
 * {rate}, {per1000}, {cost70}, {cost} and {save} already carry the tilde when
 * a program's price is unconfirmed, so never put "roughly" or its equivalent
 * immediately in front of one: it would read "roughly ~$1,330".
 */

