/**
 * Localized strings for the award-flight widget (FlightSearch.astro).
 *
 * Kept out of locales.ts for the same reason calc-locales.ts is: that registry
 * carries the chrome every localized surface shares, while everything here
 * belongs to one widget and would otherwise double the size of the file.
 *
 * WRITE THESE IN THE LANGUAGE, NOT FROM THE ENGLISH. A form is the place where
 * translated-sounding copy is most obvious, because the reader is being asked
 * to do something rather than to read. If a label cannot be read aloud
 * naturally by a speaker, rewrite it rather than tightening the translation.
 *
 * The calendar carries more than words. The widget draws its own date picker
 * (the native control obeys the browser's locale and no markup overrides it),
 * so each locale also states:
 *
 *   months / dow  the names. `dow` is ALWAYS Sunday-first — the widget
 *                 rotates it by `weekStart`, so nothing here needs reordering.
 *   weekStart     0 = Sunday, 1 = Monday. Most of Europe and Turkey start
 *                 Monday; Arabic-speaking markets vary and we use Sunday.
 *   dateOrder     "dmy" everywhere except the English page, which is "mdy".
 *   dateSep       "." in German and Turkish, "/" elsewhere.
 *   datePh        the placeholder, written in the language's own letters
 *                 (tt.mm.jjjj in German, not dd.mm.yyyy).
 *   numLocale     spells the recap date out: "20. Nov. 2026".
 *
 * Airport names are NOT translated. They come from /data/airports.json as
 * proper nouns beside their IATA codes, the fields accept free text, and
 * translating 300 entries would buy very little.
 *
 * Every locale here ships model-translated until a native speaker reviews it,
 * tracked the same way as the buy-page copy (npm run check:launch).
 */

